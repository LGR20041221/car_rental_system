"""
法定节假日判断（演示数据）。

维护近三年的中国法定节假日日期集合，用于动态定价的「节假日上浮」规则。
未覆盖的年份退化为仅按周末判断。
"""
import datetime

# 每年固定/已知的法定节假日日期（YYYY-MM-DD），按需扩充
_HOLIDAYS = {
    2025: {
        (1, 1), (1, 2), (1, 3), (1, 28), (1, 29), (1, 30), (1, 31), (2, 1),
        (2, 2), (4, 4), (4, 5), (4, 6), (5, 1), (5, 2), (5, 3), (5, 5),
        (5, 31), (6, 1), (6, 2), (10, 1), (10, 2), (10, 3), (10, 4), (10, 5),
    },
    2026: {
        (1, 1), (1, 2), (1, 3), (2, 16), (2, 17), (2, 18), (2, 19), (2, 20),
        (2, 21), (4, 4), (4, 5), (4, 6), (5, 1), (5, 2), (5, 3), (5, 5),
        (6, 19), (6, 20), (6, 21), (9, 25), (9, 26), (9, 27), (10, 1), (10, 2),
        (10, 3), (10, 4), (10, 5),
    },
}


def is_holiday(date):
    """
    判断指定日期是否为法定节假日。
    优先查静态表；未收录的年份仅按周末判断。
    """
    if not isinstance(date, datetime.date):
        date = date.date()
    year_set = _HOLIDAYS.get(date.year)
    if year_set is not None:
        return (date.month, date.day) in year_set
    return date.weekday() >= 5
